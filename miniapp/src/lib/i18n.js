export function normalizeLang(code) {
  const c = String(code || '').toLowerCase().slice(0, 2);
  if (['ru', 'uk', 'be', 'kk'].includes(c)) return 'ru';
  if (c === 'en') return 'en';
  return 'uz';
}

export function detectLang() {
  return normalizeLang(tgUser()?.language_code || navigator.language);
}

/** Tarjima maydoni: L(course, 'title', 'ru') → course.titleRu || course.title */
export function L(obj, field, lang) {
  if (!obj) return '';
  const v = lang === 'ru' ? obj[`${field}Ru`] : lang === 'en' ? obj[`${field}En`] : null;
  if (Array.isArray(v) ? v.length : v) return v;
  return obj[field];
}

