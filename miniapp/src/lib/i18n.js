export function loc(obj, field, lang) {
  if (!obj) return '';
  const suffix = lang === 'ru' ? 'Ru' : lang === 'en' ? 'En' : '';
  const value = suffix ? obj[`${field}${suffix}`] : null;
  if (Array.isArray(value)) return value.length ? value : obj[field] || [];
  return value || obj[field] || '';
}

/** Mahsulot nomining ikkinchi tildagi varianti (kartochkada kichik yozuv) */
export function altName(obj, lang) {
  if (!obj) return '';
  const alt = lang === 'uz' ? obj.nameRu : obj.name;
  const main = loc(obj, 'name', lang);
  return alt && alt !== main ? alt : '';
}

export function detectLang(tgLangCode) {
  const fromUrl = new URLSearchParams(window.location.search).get('lang');
  if (DICT[fromUrl]) return fromUrl;
  if (tgLangCode === 'ru') return 'ru';
  if (tgLangCode && tgLangCode.startsWith('en')) return 'en';
  return 'uz';
}
