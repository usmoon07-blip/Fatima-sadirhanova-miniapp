export function translate(lang, key, params) {
  const str = DICT[lang]?.[key] ?? DICT.uz[key] ?? key;
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m));
}
